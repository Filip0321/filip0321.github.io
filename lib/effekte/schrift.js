// Häufigkeit im Deutschen in Prozent (für a bis z)
const HAEUFIG = { e: 17.4, n: 9.8, i: 7.6, s: 7.3, r: 7.0, a: 6.5, t: 6.2, d: 5.1, h: 4.8, u: 4.4, l: 3.4, c: 3.1, g: 3.0, m: 2.5, o: 2.5, b: 1.9, w: 1.9, f: 1.7, k: 1.2, z: 1.1, p: 0.8, v: 0.7, j: 0.3, y: 0.1, x: 0.1, q: 0.1 };

function zahlen(zeilen) {
  let oben = 0;
  let unten = 0;
  zeilen.forEach((z, r) => {
    for (let c = 0; c < 5; c++) {
      if (z[c] !== "#") continue;
      if (r < 5) oben |= 1 << (r * 5 + c);
      else unten |= 1 << ((r - 5) * 5 + c);
    }
  });
  return [oben, unten];
}
const buchstaben = "abcdefghijklmnopqrstuvwxyz";
const klein = [...buchstaben, ".", ","].map((b) => zahlen(KLEIN[b]));
const gross = [...buchstaben.toUpperCase()].map((b) => zahlen(GROSS[b]));
const weitere = Object.keys(WEITERE).map((b) => zahlen(WEITERE[b]));
const alle = [...klein, ...gross, ...weitere];
let summe = 0;
const anteile = [...buchstaben].map((b) => (summe += HAEUFIG[b]) / 100.3);

const liste = (a) => a.map((x) => `${x}`).join(", ");
// Nummer jedes Zeichens: 0–25 klein a–z, 26 Punkt, 27 Komma, 28–53 groß A–Z, ab 54 die weiteren (Ziffern …)
export const LEER = 127; // Leerzeichen: kein Zeichen, nichts gedruckt
const NUMMER = new Map([...[...buchstaben, ".", ","].map((b, i) => [b, i]), ...[...buchstaben.toUpperCase()].map((b, i) => [b, 28 + i]), ...Object.keys(WEITERE).map((b, i) => [b, 54 + i])]);
// was die Schrift nicht hat, wird ersetzt (typografische Zeichen) oder ohne Akzent geschrieben (é → e)
const ERSATZ = { "–": "-", "—": "-", "‒": "-", "“": '"', "”": '"', "»": '"', "«": '"', "‚": ",", "‘": "'", "’": "'", "…": "...", "ẞ": "SS" };
// Text → Nummern (Zeilenumbrüche bleiben als "\n"; unbekannte Zeichen werden Leerzeichen)
export function kodiere(text) {
  const aus = [];
  for (let z of text) {
    if (z === "\n") {
      aus.push("\n");
      continue;
    }
    z = ERSATZ[z] ?? z;
    for (let t of z) {
      if (!NUMMER.has(t)) t = t.normalize("NFD")[0];
      aus.push(NUMMER.get(t) ?? LEER);
    }
  }
  return aus;
}

// GLSL: ZEICHEN_OBEN/UNTEN je Nummer (wie oben)
export const SCHRIFT_GLSL = /* glsl */ `
const int ZEICHEN_OBEN[${alle.length}] = int[${alle.length}](${liste(alle.map((x) => x[0]))});
const int ZEICHEN_UNTEN[${alle.length}] = int[${alle.length}](${liste(alle.map((x) => x[1]))});
const float HAEUFIGKEIT[26] = float[26](${anteile.map((x) => x.toFixed(4)).join(", ")});
// ist im Zeichen z an Spalte c (0–4), Zeile r (0–8) ein Punkt?
bool zeichenPunkt(int z, int c, int r) {
  if (c < 0 || c > 4 || r < 0 || r > 8 || z < 0 || z >= ${alle.length}) return false;
  int bits = r < 5 ? ZEICHEN_OBEN[z] : ZEICHEN_UNTEN[z];
  int i = (r < 5 ? r : r - 5) * 5 + c;
  return ((bits >> i) & 1) == 1;
}
// ein Buchstabe nach Häufigkeit aus einer Zufallszahl 0 bis 1
int buchstabe(float u) {
  for (int i = 0; i < 26; i++) if (u < HAEUFIGKEIT[i]) return i;
  return 4;
}
`;
